#!/usr/bin/env node
// Builds a small synthetic Choicer Voicer pack (and a zip of it) for local tests and demos.
// Usage: node scripts/make-sample-pack.mjs [outputDir]
import { spawnSync } from 'node:child_process'
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const outRoot = path.resolve(process.argv[2] ?? path.join('data', 'sample'))
const packName = 'Sample Pack'
const packDir = path.join(outRoot, packName)
const ffmpeg = process.env.FFMPEG_PATH ?? 'ffmpeg'
const archiveTool = process.env.ARCHIVE_TOOL ?? (process.platform === 'win32' ? 'tar' : 'bsdtar')
const duration = 12

function run(command, args) {
  const result = spawnSync(command, args, { stdio: ['ignore', 'ignore', 'pipe'], encoding: 'utf8' })
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(' ')} failed:\n${result.stderr ?? result.error}`)
  }
}

function ff(args) {
  run(ffmpeg, ['-hide_banner', '-nostdin', '-y', '-v', 'error', ...args])
}

const crlf = (lines) => lines.join('\r\n') + '\r\n'

rmSync(packDir, { recursive: true, force: true })
mkdirSync(packDir, { recursive: true })

ff([
  '-f', 'lavfi', '-i', `testsrc=size=640x360:rate=24:duration=${duration}`,
  '-f', 'lavfi', '-i', `sine=frequency=330:duration=${duration}`,
  '-c:v', 'libtheora', '-q:v', '6', '-pix_fmt', 'yuv420p',
  '-c:a', 'libvorbis', '-ar', '44100', '-ac', '2',
  path.join(packDir, 'dub_video.ogv'),
])
ff([
  '-f', 'lavfi', '-i', `sine=frequency=110:duration=${duration}`,
  '-ar', '44100', '-ac', '2', '-c:a', 'libmp3lame', '-b:a', '128k',
  path.join(packDir, '_backing_track.mp3'),
])
ff([
  '-f', 'lavfi', '-i', 'testsrc=size=660x364:rate=1:duration=1',
  '-frames:v', '1', path.join(packDir, 'icon.png'),
])

const lines = [
  { file: '001_Alice', time: 1.0, characters: ['Alice'], caption: '[Alice] “Hello there, is anybody home?”', freq: 520 },
  { file: '002_Bob', time: 3.5, characters: ['Bob'], caption: '[Bob] “Only me, and the cat.”', freq: 260 },
  { file: '003_Alice', time: 6.0, characters: ['Alice'], caption: '[Alice] “The cat cannot open the door!”', freq: 540 },
  { file: '004_Both', time: 9.0, characters: ['Bob', 'Alice'], caption: '[Bob] “Then who did?”', freq: 300 },
]

for (const line of lines) {
  ff([
    '-f', 'lavfi', '-i', 'anullsrc=r=48000:cl=mono', '-f', 'lavfi', '-i', `sine=frequency=${line.freq}:duration=1.6`,
    '-filter_complex', '[0:a]atrim=duration=0.15[s];[s][1:a]concat=n=2:v=0:a=1,apad=pad_dur=0.25[a]',
    '-map', '[a]', '-ar', '48000', '-ac', '1', '-c:a', 'libmp3lame', '-b:a', '96k',
    path.join(packDir, `${line.file}.mp3`),
  ])
  ff([
    '-ss', String(line.time), '-i', path.join(packDir, 'dub_video.ogv'),
    '-frames:v', '1', path.join(packDir, `${line.file}.png`),
  ])
  writeFileSync(
    path.join(packDir, `${line.file}.txt`),
    crlf([
      '[data]',
      '',
      `caption=${JSON.stringify(line.caption)}`,
      `image=${JSON.stringify(`${line.file}.png`)}`,
      `dub_timestamps=[${(line.time - 0.15).toFixed(3)}]`,
      `dub_characters=${JSON.stringify(line.characters)}`,
    ]),
  )
}

writeFileSync(
  path.join(packDir, '_pack_info.ini'),
  crlf([
    '[data]',
    '',
    'title="Sample Pack"',
    'subtitle="A synthetic test pack"',
    'icon="icon.png"',
    'authors=["Multiplayer Choicer Voicer"]',
    'readme="Generated by scripts/make-sample-pack.mjs"',
  ]),
)

const zipPath = path.join(outRoot, `${packName}.zip`)
rmSync(zipPath, { force: true })
run(archiveTool, ['-a', '-c', '-f', zipPath, '-C', outRoot, packName])

console.log(`Pack folder: ${packDir}`)
console.log(`Pack zip:    ${zipPath}`)
